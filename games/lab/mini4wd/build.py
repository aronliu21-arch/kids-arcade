#!/usr/bin/env python3
"""Build index.html from src/. Edit src/, never index.html.

If pypinyin is installed (pip install pypinyin), this also regenerates src/js/00-zy.js:
zhuyin for every Chinese character/phrase found in src/js/*.js. Without it, the
existing 00-zy.js is kept (add new characters by hand to ZYC if needed)."""
import json, pathlib, re
here = pathlib.Path(__file__).resolve().parent
src = here / "src"

CJK = re.compile(r"[一-鿿]+")
# Taiwan readings where pypinyin gives the mainland one
TW = {"期": "ㄑㄧˊ", "殼": "ㄎㄜˊ", "誰": "ㄕㄟˊ", "一": "ㄧ", "著": "˙ㄓㄜ", "不": "ㄅㄨˋ"}

def tw(z):
    # pypinyin puts the neutral-tone dot last; Taiwan textbooks put it first
    return "˙" + z[:-1] if z.endswith("˙") else z

def make_zy():
    try:
        from pypinyin import pinyin, Style
    except ImportError:
        print("pypinyin not installed: keeping existing src/js/00-zy.js")
        return
    text = "".join(p.read_text(encoding="utf-8") for p in sorted((src / "js").glob("*.js")) if p.name != "00-zy.js")
    runs = sorted(set(CJK.findall(text)))
    chars, phr = {}, {}
    for r in runs:
        zs = [TW.get(c) or tw(z[0]) for c, z in zip(r, pinyin(r, style=Style.BOPOMOFO, heteronym=False))]
        for c, z in zip(r, zs):
            chars.setdefault(c, z)
        if any(chars[c] != z for c, z in zip(r, zs)):
            phr[r] = " ".join(zs)
    out = ("/* GENERATED by build.py from the Chinese text in src/js. Do not edit by hand. */\n"
           "var ZYC=" + json.dumps(chars, ensure_ascii=False, separators=(",", ":")) + ";\n"
           "var ZYR=" + json.dumps(phr, ensure_ascii=False, separators=(",", ":")) + ";\n")
    (src / "js" / "00-zy.js").write_text(out, encoding="utf-8")
    print("zhuyin:", len(chars), "characters,", len(phr), "phrase overrides")

make_zy()
html = (src / "shell.html").read_text(encoding="utf-8")
html = re.sub(r"/\*@inc ([^*]+)\*/", lambda m: "".join((src / f).read_text(encoding="utf-8") for f in m.group(1).split()), html)
(here / "index.html").write_text(html, encoding="utf-8")
print("built", here.name, len(html.encode("utf-8")), "bytes")
